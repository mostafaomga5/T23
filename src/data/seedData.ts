/**
 * Generates crisp, self-contained SVG Data-URI document specimens
 * so every prototype document has a realistic, high-contrast scan preview
 * that never breaks or relies on external image hosts.
 */
function escapeXml(str: string): string {
  return str
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;');
}

